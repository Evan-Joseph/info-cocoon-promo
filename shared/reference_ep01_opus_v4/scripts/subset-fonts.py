#!/usr/bin/env python3
"""Subset Noto Serif SC / Noto Sans SC / EB Garamond Italic / JetBrains Mono to the glyphs used in src/film/*.
Writes src/film/fontdata.ts (base64 woff2) so headless Chromium never renders tofu and no network is needed."""
import base64, glob, io, os, subprocess, sys, tempfile, urllib.request
from fontTools.ttLib import TTFont

SRC = "/tmp/fonts"
os.makedirs(SRC, exist_ok=True)
URLS = {
    "NotoSerifSC[wght].ttf": "https://github.com/google/fonts/raw/main/ofl/notoserifsc/NotoSerifSC%5Bwght%5D.ttf",
    "NotoSansSC[wght].ttf": "https://github.com/google/fonts/raw/main/ofl/notosanssc/NotoSansSC%5Bwght%5D.ttf",
    "EBGaramond-Italic[wght].ttf": "https://github.com/google/fonts/raw/main/ofl/ebgaramond/EBGaramond-Italic%5Bwght%5D.ttf",
    "JetBrainsMono[wght].ttf": "https://github.com/google/fonts/raw/main/ofl/jetbrainsmono/JetBrainsMono%5Bwght%5D.ttf",
}
for fname, url in URLS.items():
    fpath = os.path.join(SRC, fname)
    if not os.path.exists(fpath) or os.path.getsize(fpath) < 50_000:
        urllib.request.urlretrieve(url, fpath)

JOBS = {
    "serif": ("NotoSerifSC[wght].ttf", "wght=600:900"),
    "sans": ("NotoSansSC[wght].ttf", "wght=500:900"),
    "garamond": ("EBGaramond-Italic[wght].ttf", "wght=400:800"),
    "mono": ("JetBrainsMono[wght].ttf", "wght=100:800"),
}

chars = set()
for f in glob.glob("src/film/*.ts*") + glob.glob("src/*.tsx"):
    if f.endswith("fontdata.ts"):
        continue
    chars |= set(open(f, encoding="utf-8").read())
chars |= set(" 0123456789:+-–—·×→%¥$<>=.,;:!?()[]{}/&'\"…，。？：；、「」《》【】“”‘’✕✓")
chars |= set("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz")
text = "".join(sorted(c for c in chars if ord(c) >= 0x20))
open("/tmp/fonts/chars.txt", "w", encoding="utf-8").write(text)
print("glyph set:", len(text))

out = {}
for key, (fname, axis) in JOBS.items():
    tmp = tempfile.mkdtemp()
    sub = os.path.join(tmp, "sub.ttf")
    subprocess.check_call([sys.executable, "-m", "fontTools.subset", os.path.join(SRC, fname), "--text-file=/tmp/fonts/chars.txt", f"--output-file={sub}", "--layout-features=*", "--no-hinting", "--drop-tables+=DSIG"])
    inst = os.path.join(tmp, "inst.ttf")
    subprocess.check_call([sys.executable, "-m", "fontTools.varLib.instancer", sub, axis, "-o", inst])
    font = TTFont(inst)
    font.flavor = "woff2"
    buf = io.BytesIO()
    font.save(buf)
    out[key] = base64.b64encode(buf.getvalue()).decode()
    print(key, len(buf.getvalue()) // 1024, "KB")

with open("src/film/fontdata.ts", "w") as fh:
    fh.write("// AUTO-GENERATED by scripts/subset-fonts.py — do not edit.\nexport const FONT_DATA = {\n")
    for k, v in out.items():
        fh.write(f'  {k}: "{v}",\n')
    fh.write("} as const;\n")
